export const getMinMockData = (originalData) => {
  const walk = (obj) => {
    if (obj === null || obj === undefined) return obj;
    if (typeof obj === "number") return 0;
    if (typeof obj === "string") {
      if (obj.startsWith("Order #")) return "Đơn #0";
      return obj;
    }
    if (Array.isArray(obj)) {
      return obj.map(walk);
    }
    if (typeof obj === "object") {
      const result = {};
      for (const key in obj) {
        if (key === "name" || key === "label" || key === "periodLabel" || key === "prevPeriodLabel" || key === "range" || key === "month") {
          result[key] = obj[key];
        } else {
          result[key] = walk(obj[key]);
        }
      }
      return result;
    }
    return obj;
  };
  return walk(originalData);
};

